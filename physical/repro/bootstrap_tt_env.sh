set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PROJECT_ROOT=$(printenv TINYLPU_PROJECT_ROOT 2>/dev/null || true)
if [ -z "$PROJECT_ROOT" ]; then PROJECT_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd); fi
LOCK_FILE="$SCRIPT_DIR/versions.lock"
lock() { awk -F= -v k="$1" '$1 == k {print substr($0,index($0,"=")+1); exit}' "$LOCK_FILE"; }
IMAGE=$(lock LIBRELANE_IMAGE)
IMAGE_REF=$(lock LIBRELANE_IMAGE_REF)
IMAGE_ID=$(lock LIBRELANE_IMAGE_ID)
DIGEST1=$(lock LIBRELANE_IMAGE_REPO_DIGEST_1)
DIGEST2=$(lock LIBRELANE_IMAGE_REPO_DIGEST_2)
PDK_COMMIT=$(lock SKY130A_OPEN_PDKS_COMMIT)
PDK_ROOT=$(printenv TINYLPU_PDK_ROOT 2>/dev/null || true)
if [ -z "$PDK_ROOT" ]; then PDK_ROOT="$PROJECT_ROOT/physical/pdk"; fi
VENV="$PROJECT_ROOT/physical/container-venv"
VENDOR="$PROJECT_ROOT/physical/vendor"
TMP_BASE=$(printenv TMPDIR 2>/dev/null || true)
if [ -z "$TMP_BASE" ]; then TMP_BASE=/tmp; fi
PODMAN_ROOT=$(printenv TINYLPU_PODMAN_ROOT 2>/dev/null || true)
if [ -z "$PODMAN_ROOT" ]; then PODMAN_ROOT="$TMP_BASE/tinylpu-tt-podman-overlay"; fi
PODMAN_RUNROOT=$(printenv TINYLPU_PODMAN_RUNROOT 2>/dev/null || true)
if [ -z "$PODMAN_RUNROOT" ]; then PODMAN_RUNROOT="$TMP_BASE/tinylpu-tt-podman-overlay-run"; fi
errors=0
warnings=0
fail() { errors=$((errors+1)); echo "FAIL: $*" >&2; }
warn() { warnings=$((warnings+1)); echo "WARN: $*" >&2; }
pass() { echo "PASS: $*"; }
usage() { echo "Usage: $0 --check | --bootstrap --cache-root ABSOLUTE_DIR [--pull-image]"; }

mode=""
cache_root=""
pull=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --check) [ -z "$mode" ] || { echo "choose one mode" >&2; exit 2; }; mode=check; shift;;
    --bootstrap) [ -z "$mode" ] || { echo "choose one mode" >&2; exit 2; }; mode=bootstrap; shift;;
    --cache-root) [ "$#" -ge 2 ] || { echo "missing cache path" >&2; exit 2; }; cache_root=$2; shift 2;;
    --pull-image) pull=1; shift;;
    --help|-h) usage; exit 0;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2;;
  esac
done
[ -n "$mode" ] || { usage >&2; exit 2; }

if [ "$mode" = bootstrap ]; then
  case "$cache_root" in /*) ;; *) echo "--cache-root must be absolute" >&2; exit 2;; esac
  [ ! -e "$cache_root" ] || { echo "refusing existing cache root: $cache_root" >&2; exit 2; }
  case "$cache_root" in */physical/work|*/physical/work/*) echo "refusing physical/work" >&2; exit 2;; esac
  mkdir -p "$cache_root/podman-root" "$cache_root/podman-runroot"
  printf '%s\n' '# Generated by bootstrap_tt_env.sh' "export TINYLPU_PODMAN_ROOT=$cache_root/podman-root" "export TINYLPU_PODMAN_RUNROOT=$cache_root/podman-runroot" "export TINYLPU_PDK_ROOT=$PDK_ROOT" > "$cache_root/env.sh"
  if [ "$pull" -eq 1 ]; then
    command -v podman >/dev/null 2>&1 || { echo "podman is required" >&2; exit 2; }
    podman --root "$cache_root/podman-root" --runroot "$cache_root/podman-runroot" --storage-driver=overlay --storage-opt overlay.ignore_chown_errors=true pull "$IMAGE_REF"
    podman --root "$cache_root/podman-root" --runroot "$cache_root/podman-runroot" --storage-driver=overlay --storage-opt overlay.ignore_chown_errors=true tag "$IMAGE_REF" "$IMAGE"
  else
    echo "prepared fresh cache without downloads: $cache_root"
  fi
  echo "no project work directory was created or overwritten"
  exit 0
fi
check_git() {
  label=$1
  path=$2
  expected=$3
  if [ ! -d "$path/.git" ]; then fail "$label checkout missing: $path"; return; fi
  actual=$(git -C "$path" rev-parse HEAD 2>/dev/null || true)
  if [ "$actual" = "$expected" ]; then
    pass "$label $actual"
  else
    actual_display=$actual
    [ -n "$actual_display" ] || actual_display=none
    fail "$label expected $expected got $actual_display"
  fi
}
check_git tt-template "$VENDOR/ttsky-verilog-template" "$(lock TT_TEMPLATE_COMMIT)"
check_git tt-gds-action "$VENDOR/tt-gds-action" "$(lock TT_GDS_ACTION_COMMIT)"
check_git tt-support-tools "$VENDOR/tt-support-tools" "$(lock TT_SUPPORT_TOOLS_COMMIT)"
check_git ciel-action "$VENDOR/ciel-action" "$(lock CIEL_ACTION_COMMIT)"

sky130="$PDK_ROOT/sky130A"
[ -d "$sky130" ] || fail "PDK missing: $sky130"
if [ -d "$sky130" ]; then
  [ -r "$sky130/SOURCES" ] && grep -Fq "$PDK_COMMIT" "$sky130/SOURCES" && pass "PDK open_pdks $PDK_COMMIT" || fail "PDK SOURCES mismatch"
  [ -d "$sky130/libs.ref/sky130_fd_sc_hd" ] && pass "PDK sky130_fd_sc_hd" || fail "PDK sky130_fd_sc_hd missing"
fi

CIEL=$(printenv TINYLPU_CIEL_BIN 2>/dev/null || true)
if [ -z "$CIEL" ]; then CIEL="$PROJECT_ROOT/.venv-tt-physical/bin/ciel"; fi
if [ -x "$CIEL" ]; then
  CIEL_VER=$("$CIEL" --version 2>/dev/null | head -1 || true)
  printf '%s' "$CIEL_VER" | grep -Fq "Ciel v$(lock CIEL_VERSION)" && pass "$CIEL_VER" || fail "Ciel version mismatch: $CIEL_VER"
else
  warn "Ciel executable not found; existing PDK was checked without re-enabling it"
fi

command -v podman >/dev/null 2>&1 || fail "podman not found"
command -v git >/dev/null 2>&1 || fail "git not found"
if [ ! -d "$PODMAN_ROOT" ] || [ ! -d "$PODMAN_RUNROOT" ]; then
  fail "Podman cache roots absent: $PODMAN_ROOT and $PODMAN_RUNROOT"
  podman_ready=0
else
  podman_ready=1
fi
podman_cmd=(podman --root "$PODMAN_ROOT" --runroot "$PODMAN_RUNROOT" --storage-driver=overlay --storage-opt overlay.ignore_chown_errors=true)
run_podman() { podman --root "$PODMAN_ROOT" --runroot "$PODMAN_RUNROOT" --storage-driver=overlay --storage-opt overlay.ignore_chown_errors=true "$@"; }
if [ "$podman_ready" -eq 1 ] && command -v podman >/dev/null 2>&1; then
  podman_version=$(podman --version 2>/dev/null || true)
  printf '%s' "$podman_version" | grep -Fq "$(lock PODMAN_VERSION)" && pass "$podman_version" || fail "Podman version mismatch: $podman_version"
  rootless=$(run_podman info --format '{{.Host.Security.Rootless}}' 2>/dev/null || true)
  [ "$rootless" = true ] && pass "rootless Podman" || fail "Podman is not confirmed rootless: $rootless"
fi
image_id=""
if [ "$podman_ready" -eq 1 ] && command -v podman >/dev/null 2>&1; then
  image_id=$(run_podman image inspect "$IMAGE" --format '{{.Id}}' 2>/dev/null || true)
  digests=$(run_podman image inspect "$IMAGE" --format '{{.RepoDigests}}' 2>/dev/null || true)
  if [ -z "$image_id" ]; then
    fail "image absent: $IMAGE"
  elif printf '%s' "$image_id" | grep -Fq "$IMAGE_ID"; then
    pass "image ID $IMAGE_ID"
  else
    fail "image ID mismatch: $image_id"
  fi
  printf '%s' "$digests" | grep -Fq "$DIGEST1" && pass "image digest $DIGEST1" || fail "missing image digest $DIGEST1"
  printf '%s' "$digests" | grep -Fq "$DIGEST2" && pass "image digest $DIGEST2" || fail "missing image digest $DIGEST2"
fi
if [ "$podman_ready" -eq 1 ] && [ -n "$image_id" ]; then
  pyver=$(run_podman run --rm --network=none --security-opt label=disable --entrypoint python3 "$IMAGE" --version 2>/dev/null || true)
  printf '%s' "$pyver" | grep -Fq "Python $(lock CONTAINER_PYTHON_VERSION)" && pass "$pyver" || fail "container Python mismatch: $pyver"
  orver=$(run_podman run --rm --network=none --security-opt label=disable --entrypoint openroad "$IMAGE" -version 2>/dev/null || true)
  printf '%s' "$orver" | grep -Fq "$(lock OPENROAD_COMMIT)" && pass "OpenROAD $(lock OPENROAD_COMMIT)" || fail "OpenROAD mismatch: $orver"
  llver=$(run_podman run --rm --network=none --security-opt label=disable --entrypoint python3 "$IMAGE" -c 'import importlib.metadata as m; print(m.version("librelane"))' 2>/dev/null || true)
  [ "$llver" = "$(lock LIBRELANE_VERSION)" ] && pass "LibreLane $llver" || fail "LibreLane mismatch: $llver"
fi

[ -d "$VENV" ] || fail "container venv missing: $VENV"
if [ -d "$VENV" ] && [ "$podman_ready" -eq 1 ] && [ -n "$image_id" ]; then
  nix_lib_dirs=$(run_podman run --rm --network=none --security-opt label=disable --entrypoint sh "$IMAGE" -lc 'find /nix/store -type f -name "lib*.so*" -printf "%h\n" 2>/dev/null | sort -u | paste -sd:' 2>/dev/null || true)
  probe=$(run_podman run --rm --network=none --security-opt label=disable -v "$VENV:/workspace/venv:ro" -e "LD_LIBRARY_PATH=/workspace/venv/lib/python3.13/site-packages/cocotb/libs:$nix_lib_dirs" --entrypoint /workspace/venv/bin/python "$IMAGE" -c 'import importlib.metadata as m, cairosvg, cairocffi, cocotb, cocotb_tools, gdstk, klayout.db as kdb, numpy, sys; print("python=" + sys.version.split()[0]); print("cocotb=" + cocotb.__version__); print("gdstk=" + gdstk.__version__); print("klayout=" + m.version("klayout")); print("numpy=" + numpy.__version__); print("cairosvg=" + cairosvg.__version__); print("cairocffi=" + cairocffi.__version__); print("yowasp-yosys=" + m.version("yowasp-yosys")); print("klayout_db=" + kdb.__file__)' 2>&1 || true)
  printf '%s' "$probe" | grep -Fq "python=$(lock CONTAINER_PYTHON_VERSION)" && printf '%s' "$probe" | grep -Fq "cocotb=$(lock CONTAINER_COCOTB_VERSION)" && printf '%s' "$probe" | grep -Fq "gdstk=$(lock CONTAINER_GDSTK_VERSION)" && printf '%s' "$probe" | grep -Fq "klayout=$(lock CONTAINER_KLAYOUT_VERSION)" && printf '%s' "$probe" | grep -Fq "numpy=$(lock CONTAINER_NUMPY_VERSION)" && printf '%s' "$probe" | grep -Fq "cairosvg=$(lock CONTAINER_CAIROSVG_VERSION)" && printf '%s' "$probe" | grep -Fq "yowasp-yosys=$(lock CONTAINER_YOWASP_YOSYS_VERSION)" && pass "cocotb/gdstk/klayout/Cairo/Nix-runtime import probe" || fail "container venv probe: $probe"
fi

if [ "$errors" -ne 0 ]; then
  echo "environment check failed: $errors error(s), $warnings warning(s)" >&2
  exit 1
fi
echo "environment check passed: $warnings warning(s)"
exit 0
